export const activeProducts: Product[] = products.filter((p) => p.status === "active");

export function getProductBySlug(slug: string): Product | undefined {
  return activeProducts.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return activeProducts.find((p) => p.id === id);
}

export function getProductsByCategory(category: Category): Product[] {
  return activeProducts.filter((p) => p.category === category);
}

export function getProductsBySubcategory(category: Category, subcategory: string): Product[] {
  return activeProducts.filter((p) => p.category === category && p.subcategory === subcategory);
}

export function getCollectionProducts(collection: string): Product[] {
  return activeProducts.filter((p) => p.collection === collection);
}

export function getSaleProducts(): Product[] {
  return activeProducts.filter((p) => p.discountPrice != null);
}

export function getNewArrivals(limit?: number): Product[] {
  const items = activeProducts.filter((p) => p.isNew);
  return limit ? items.slice(0, limit) : items;
}

export function getFeaturedProducts(limit?: number): Product[] {
  const items = activeProducts.filter((p) => p.featured);
  return limit ? items.slice(0, limit) : items;
}

export function getBestSellers(limit?: number): Product[] {
  const items = activeProducts.filter((p) => p.bestseller);
  return limit ? items.slice(0, limit) : items;
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const sameSub = activeProducts.filter(
    (p) => p.subcategory === product.subcategory && p.id !== product.id,
  );
  const sameCategory = activeProducts.filter(
    (p) => p.category === product.category && p.id !== product.id && p.subcategory !== product.subcategory,
  );
  const sameCollection = activeProducts.filter(
    (p) => p.collection && p.collection === product.collection && p.id !== product.id,
  );
  const pool = [...sameSub, ...sameCollection, ...sameCategory];
  const seen = new Set<string>();
  const out: Product[] = [];
  for (const p of pool) {
    if (seen.has(p.id)) continue;
    seen.add(p.id);
    out.push(p);
    if (out.length >= limit) break;
  }
  if (out.length < limit) {
    for (const p of activeProducts) {
      if (out.length >= limit) break;
      if (!seen.has(p.id)) {
        seen.add(p.id);
        out.push(p);
      }
    }
  }
  return out;
}

/** Lightweight client-safe text search. */
export function searchProducts(query: string, limit = 12): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const terms = q.split(/\s+/).filter(Boolean);
  const scored = activeProducts
    .map((p) => {
      const haystack = [
        p.name,
        p.description,
        p.category,
        p.subcategory,
        p.collection ?? "",
        p.attributes.material,
        p.attributes.fit,
        ...p.colors.map((cl) => cl.name),
      ]
        .join(" ")
        .toLowerCase();
      let score = 0;
      for (const t of terms) {
        if (haystack.includes(t)) score += 1;
        if (p.name.toLowerCase().includes(t)) score += 2;
      }
      return { p, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || a.p.price - b.p.price);
  return scored.slice(0, limit).map((x) => x.p);
}
